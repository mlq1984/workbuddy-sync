#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""办公文书框架生成。
用法：
  python3 template-gen.py [类型] [主题]
类型：申请/证明/请假/委托/协议/通知
"""
import sys

T = {
    "申请": ["标题：关于{主题}的申请", "致：××", "一、申请事项", "二、申请理由", "落款：申请人/日期"],
    "证明": ["标题：{主题}证明", "正文：兹证明 {主体} 于 {时间} {事实}", "落款：出具单位/日期/盖章"],
    "请假": ["标题：请假条", "致：××", "请假时间：{..} ｜ 事由：{..}", "恳请批准。", "落款：姓名/日期"],
    "委托": ["标题：授权委托书", "委托人：{..} ｜ 受托人：{..}", "委托事项与权限：{..}", "期限：{..}", "签署：双方/日期"],
    "协议": ["标题：{主题}协议", "甲方：{..} ｜ 乙方：{..}", "一、合作内容", "二、双方权利义务", "三、期限与费用", "四、签署"],
    "通知": ["标题：关于{主题}的通知", "主送：{..}", "一、缘由", "二、事项", "三、要求", "落款：单位/日期"],
}

def main():
    typ = sys.argv[1] if len(sys.argv) > 1 and sys.argv[1] in T else "申请"
    topic = sys.argv[2] if len(sys.argv) > 2 else "事项"
    out = []
    out.append("【%s 框架】" % typ)
    for s in T[typ]:
        out.append(s.replace("{主题}", topic))
    out.append("-" * 34)
    out.append("提示：填入真实信息；合同/协议重大事项咨询律师。")
    return "\n".join(out)

if __name__ == "__main__":
    print(main())
