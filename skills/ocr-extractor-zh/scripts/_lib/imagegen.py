"""纯标准库 PNG 生成器（用于生成 OCR 测试图，使测试不依赖任何图像库）。

只用 ``zlib`` + ``struct`` 写真正的 PNG，再用内置点阵字体画字。
这样在 macOS / Windows / Linux、以及无网络无第三方库的 CI 上都能造出「有字可识别」的图，
从而把 OCR 引擎的**端到端**路径纳入自动验证（而不是只测参数解析）。
"""
