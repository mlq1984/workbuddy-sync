GLYPH_W = 5
GLYPH_H = 7


class Canvas:
    """一张 RGB 画布，可画点阵文字，最后写出 PNG。"""

    def __init__(self, width, height, background=(255, 255, 255)):
        # type: (int, int, Tuple[int, int, int]) -> None
        self.width = width
        self.height = height
        self.pixels = [list(background) * width for _ in range(height)]  # type: List[List[int]]

    def set_pixel(self, x, y, color=(0, 0, 0)):
        # type: (int, int, Tuple[int, int, int]) -> None
        if 0 <= x < self.width and 0 <= y < self.height:
            base = x * 3
            self.pixels[y][base:base + 3] = list(color)

    def fill_rect(self, x, y, w, h, color=(0, 0, 0)):
        # type: (int, int, int, int, Tuple[int, int, int]) -> None
        for dy in range(h):
            for dx in range(w):
                self.set_pixel(x + dx, y + dy, color)

    def draw_text(self, x, y, text, scale=3, color=(0, 0, 0), spacing=2):
        # type: (int, int, str, int, Tuple[int, int, int], int) -> int
        """画一行大写点阵文字，返回结束的 x 坐标。小写字母自动转大写。"""
        cursor = x
        for char in text:
            glyph = FONT_5X7.get(char.upper())
            if glyph is None:
                cursor += (GLYPH_W + spacing) * scale
                continue
            for row_index, row_bits in enumerate(glyph):
                for col in range(GLYPH_W):
                    if row_bits & (1 << (GLYPH_W - 1 - col)):
                        self.fill_rect(
                            cursor + col * scale,
                            y + row_index * scale,
                            scale,
                            scale,
                            color,
                        )
            cursor += (GLYPH_W + spacing) * scale
        return cursor

    def text_width(self, text, scale=3, spacing=2):
        # type: (str, int, int) -> int
        return len(text) * (GLYPH_W + spacing) * scale

    def to_png_bytes(self):
        # type: () -> bytes
        raw = bytearray()
        for row in self.pixels:
            raw.append(0)  # filter type 0 (None)
            raw.extend(row)
        return _png(self.width, self.height, bytes(raw))


def render_lines(lines, scale=4, padding=24, line_gap=14, background=(255, 255, 255)):
    # type: (Sequence[str], int, int, int, Tuple[int, int, int]) -> bytes
    """把若干行文字渲染成 PNG 字节。"""
    line_height = GLYPH_H * scale
    longest = max([len(ln) for ln in lines] + [1])
    width = padding * 2 + longest * (GLYPH_W + 2) * scale
    height = padding * 2 + len(lines) * line_height + max(0, len(lines) - 1) * line_gap
    canvas = Canvas(width, height, background)
    y = padding
    for line in lines:
        canvas.draw_text(padding, y, line, scale=scale)
        y += line_height + line_gap
    return canvas.to_png_bytes()


def write_png(path, lines, scale=4, padding=24, line_gap=14):
    # type: (str, Sequence[str], int, int, int) -> str
    data = render_lines(lines, scale=scale, padding=padding, line_gap=line_gap)
    with open(path, "wb") as handle:
        handle.write(data)
    return path


def _png(width, height, raw_scanlines):
    # type: (int, int, bytes) -> bytes
    def chunk(tag, payload):
        body = tag + payload
        return (
            struct.pack(">I", len(payload))
            + body
            + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)
        )

    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)  # 8bit truecolor
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", header)
        + chunk(b"IDAT", zlib.compress(raw_scanlines, 9))
        + chunk(b"IEND", b"")
    )
