param(
    [string]$RuntimeRoot = (Join-Path $env:USERPROFILE '.openvino'),
    [string]$ArchiveDir,
    [string]$OutFile
)

$ErrorActionPreference = 'Stop'

$SkillRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
if (-not $OutFile) { $OutFile = Join-Path $SkillRoot 'runtime-checksums.candidate.txt' }

if (-not $ArchiveDir -or -not (Test-Path -LiteralPath $ArchiveDir -PathType Container)) {
    throw 'Specify -ArchiveDir containing the original ppocr-windows-x64.zip and pdfium.zip. Extracted binaries cannot reproduce archive hashes.'
}

$Targets = @(
    [pscustomobject]@{ Name = 'ppocr-windows-x64.zip'; Path = (Join-Path $ArchiveDir 'ppocr-windows-x64.zip') },
    [pscustomobject]@{ Name = 'pdfium.zip'; Path = (Join-Path $ArchiveDir 'pdfium.zip') }
)
foreach ($ModelName in @('PP-OCRv5_server_det_ov', 'PP-OCRv5_server_rec_ov')) {
    $ModelFiles = @('inference.xml', 'inference.bin', 'inference.yml')
    if ($ModelName -match '_det_') { $ModelFiles += 'inference_960.xml' }
    if ($ModelName -match '_rec_') { $ModelFiles += @('inference_320.xml', 'inference_480.xml', 'inference_640.xml', 'inference_800.xml', 'inference_1280.xml') }
    foreach ($FileName in $ModelFiles) {
        $AssetName = "$ModelName/$FileName"
        $Targets += [pscustomobject]@{ Name = $AssetName; Path = (Join-Path (Join-Path $RuntimeRoot 'models') $AssetName) }
    }
}

$Entries = @()
foreach ($Target in $Targets) {
    if (-not (Test-Path -LiteralPath $Target.Path -PathType Leaf) -or (Get-Item -LiteralPath $Target.Path).Length -eq 0) {
        throw "Required asset is missing or empty: $($Target.Path)"
    }
    $Hash = (Get-FileHash -LiteralPath $Target.Path -Algorithm SHA256).Hash.ToLowerInvariant()
    $Entries += [pscustomobject]@{ Hash = $Hash; Name = $Target.Name }
}

$Header = @(
    '# Candidate SHA-256 pins for local-ocr-npu; NOT independently authenticated.',
    '#',
    ('# Generated by scripts/pin-runtime-checksums.ps1 on ' + (Get-Date -Format 'yyyy-MM-dd HH:mm:ss')),
    '# Format (identical to `sha256sum` output): <64-hex-digest>  <asset-name>',
    '#',
    '# Compare every entry against a trusted publisher or independently verified',
    '# release before promoting this candidate to runtime-checksums.txt.',
    '# Hashing a local download alone does not establish its authenticity.',
    '#'
)

$Body = $Entries | Sort-Object Name | ForEach-Object { ('{0}  {1}' -f $_.Hash, $_.Name) }

$Content = ($Header + $Body) -join "`n"
Set-Content -LiteralPath $OutFile -Value $Content -Encoding ASCII

Write-Host "[OK] Wrote $($Entries.Count) candidate digest(s) to: $OutFile"
Write-Warning 'Candidate hashes are not trusted pins until independently verified. Do not publish them automatically.'
$Body | ForEach-Object { Write-Host "     $_" }
