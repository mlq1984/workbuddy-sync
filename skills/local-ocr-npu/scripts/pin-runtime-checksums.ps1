param(
    [string]$RuntimeRoot = (Join-Path $env:USERPROFILE '.openvino'),
    [string]$OutFile
)

$ErrorActionPreference = 'Stop'

# Regenerates runtime-checksums.txt for the local-ocr-npu skill by hashing the
# assets already cached under %USERPROFILE%\.openvino.
#
# Run this on a machine you trust, AFTER a full successful first run, then ship
# the produced file inside the skill package. run.sh / download.ps1 verify every
# subsequent download against those digests.
#
# Usage:
#   scripts\pin-runtime-checksums.ps1
#   scripts\pin-runtime-checksums.ps1 -RuntimeRoot D:\cache\.openvino -OutFile .\runtime-checksums.txt

$SkillRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
if (-not $OutFile) { $OutFile = Join-Path $SkillRoot 'runtime-checksums.txt' }

if (-not (Test-Path $RuntimeRoot)) {
    Write-Host "[ERROR] Runtime root not found: $RuntimeRoot"
    Write-Host '        Run the skill once so the assets are downloaded, then retry.'
    exit 1
}

$Targets = @(
    (Join-Path $RuntimeRoot 'bin'),
    (Join-Path $RuntimeRoot 'models')
)

$Entries = @()
foreach ($dir in $Targets) {
    if (-not (Test-Path $dir)) { continue }
    # Only hash real assets, never the download scratch files.
    $files = Get-ChildItem -LiteralPath $dir -Recurse -File |
        Where-Object { $_.Name -notlike '*.partial' -and $_.Name -notlike '*.sha' -and $_.Extension -ne '.log' }
    foreach ($f in $files) {
        $hash = (Get-FileHash -LiteralPath $f.FullName -Algorithm SHA256).Hash.ToLower()
        $Entries += [pscustomobject]@{ Hash = $hash; Name = $f.Name }
    }
}

if ($Entries.Count -eq 0) {
    Write-Host "[ERROR] No assets found under $RuntimeRoot."
    Write-Host '        Expected bin\ (ppocr.exe, openvino.dll, pdf2png.exe, pdfium.dll) and models\.'
    exit 1
}

$Unique = $Entries | Sort-Object Name -Unique

$Header = @(
    '# runtime-checksums.txt -- SHA-256 pins for the assets local-ocr-npu downloads.',
    '#',
    '# Generated by scripts/pin-runtime-checksums.ps1 on ' + (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'),
    '# Format (identical to `sha256sum` output): <64-hex-digest>  <asset-name>',
    '#',
    '# run.sh and download.ps1 verify each download against these digests.',
    '# An asset with no entry here is downloaded with a warning instead of a check;',
    '# an entry that does not match causes the download to be deleted and the run to abort.',
    '#'
)

$Body = $Unique | ForEach-Object { ('{0}  {1}' -f $_.Hash, $_.Name) }

$Content = ($Header + $Body) -join "`n"
Set-Content -LiteralPath $OutFile -Value $Content -Encoding UTF8

Write-Host "[OK] Wrote $($Unique.Count) digest(s) to: $OutFile"
$Body | ForEach-Object { Write-Host "     $_" }
